import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';

const require = createRequire(import.meta.url);
const postcss = require('postcss');

const ROOT = path.resolve(import.meta.dirname, '..');
const INPUT = path.join(ROOT, 'src/app/globals.css');
const COMPILED = path.join(ROOT, 'scripts/compiled-tailwind.css');
const OUT_DIR = path.join(ROOT, 'src/lib/generated-tailwind');

/** Class strings on each gallery source component (must match host JSX). */
const WIDGET_CLASSES = {
  'widget-1':
    'rounded-xl bg-parity-accent-soft px-4 py-3 text-parity-ink shadow-sm ring-1 ring-parity-accent/30',
  'widget-2':
    'rounded-xl bg-yellow-300 px-4 py-3 text-zinc-950 shadow-sm ring-2 ring-fuchsia-600',
};

function escapeClassSelector(className) {
  return `.${className.replace(/([^a-zA-Z0-9_-])/g, '\\$1')}`;
}

function unquote(value = '') {
  return value.replace(/^["']|["']$/g, '');
}

function collectVarNames(cssText) {
  const names = new Set();
  for (const match of cssText.matchAll(/var\((--[\w-]+)/g)) {
    names.add(match[1]);
  }
  for (const match of cssText.matchAll(/(--tw-[\w-]+)\s*:/g)) {
    names.add(match[1]);
  }
  return names;
}

const HOST_ROOT_VALUES = {
  '--tw-inset-shadow': '0 0 #0000',
  '--tw-inset-ring-shadow': '0 0 #0000',
  '--tw-ring-offset-shadow': '0 0 #0000',
  '--tw-ring-offset-width': '0px',
};

function formatRule(rule) {
  const body = rule.nodes
    .map((node) => {
      if (node.type === 'decl') {
        return `  ${node.prop}: ${node.value};`;
      }
      if (node.type === 'atrule') {
        const inner = node.nodes
          ?.filter((child) => child.type === 'decl')
          .map((child) => `    ${child.prop}: ${child.value};`)
          .join('\n');
        return `  @${node.name} ${node.params} {\n${inner}\n  }`;
      }
      return '';
    })
    .filter(Boolean)
    .join('\n');
  return `${rule.selector} {\n${body}\n}`;
}

const config = (await import('../postcss.config.mjs')).default;
const sourceCss = await fs.readFile(INPUT, 'utf8');
const plugins = (config.plugins ?? []).map((plugin) =>
  typeof plugin === 'string' ? require(plugin) : plugin
);
const compiled = await postcss(plugins).process(sourceCss, {
  from: INPUT,
  to: COMPILED,
});
await fs.writeFile(COMPILED, compiled.css);

const root = postcss.parse(compiled.css);

await fs.mkdir(OUT_DIR, { recursive: true });

for (const [slug, classString] of Object.entries(WIDGET_CLASSES)) {
  const classNames = classString.trim().split(/\s+/);
  const classRules = [];
  const usedVars = new Set();

  for (const className of classNames) {
    const selector = escapeClassSelector(className);
    /** @type {import('postcss').Rule | undefined} */
    let match;
    root.walkRules((rule) => {
      if (rule.selector === selector) {
        match = rule;
      }
    });
    if (!match) {
      throw new Error(`No compiled rule for ${selector}`);
    }
    const css = formatRule(match);
    classRules.push({ className, css });
    for (const name of collectVarNames(css)) {
      usedVars.add(name);
    }
  }

  const variables = [];

  root.walkDecls((decl) => {
    if (!usedVars.has(decl.prop)) {
      return;
    }
    const parent = decl.parent;
    if (parent?.type === 'rule' && parent.selector.includes(':root')) {
      if (!variables.some((item) => item.name === decl.prop && item.source === 'theme')) {
        variables.push({
          name: decl.prop,
          value: decl.value,
          source: 'theme',
        });
      }
    }
  });

  root.walkAtRules('property', (atrule) => {
    const name = atrule.params.trim();
    if (!usedVars.has(name)) {
      return;
    }
    const parts = {};
    atrule.walkDecls((decl) => {
      parts[decl.prop] = decl.value;
    });
    const initialValue = unquote(parts['initial-value'] ?? '');
    const syntax = unquote(parts.syntax ?? '*');
    variables.push({
      name,
      value: initialValue || syntax,
      source: 'property',
    });
  });

  const minimumVariables = [
    ...variables
      .filter((item) => item.source === 'theme')
      .sort((a, b) => a.name.localeCompare(b.name)),
    ...Object.entries(HOST_ROOT_VALUES)
      .filter(([name]) => usedVars.has(name))
      .map(([name, value]) => ({
        name,
        value,
        source: 'property',
      })),
  ];

  const file = path.join(OUT_DIR, `${slug}.ts`);
  const contents = `/**
 * Snapshot of Tailwind's PostCSS output for this gallery widget.
 * Regenerated by \`npm run extract:widget-css\`.
 */
export const widgetClassNames = ${JSON.stringify(classNames, null, 2)} as const;

export const widgetCssVariables = ${JSON.stringify(minimumVariables, null, 2)} as const;

export const widgetClassRules = ${JSON.stringify(classRules, null, 2)} as const;
`;
  await fs.writeFile(file, contents);
  console.log(`Wrote ${file}`);
}
